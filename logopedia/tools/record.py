"""Records every story line with the Kokoro neural voice.

Usage (from the logopedia folder):
    node tools/extract-lines.js > lines.json
    python tools/record.py lines.json --model kokoro.onnx --voices voices.bin

Needs: pip install kokoro-onnx soundfile numpy, and ffmpeg on the PATH.
Model files: https://github.com/thewh1teagle/kokoro-onnx/releases (model-files-v1.0).
Only lines without a recording are generated; recordings for lines that no
longer exist are deleted. Writes audio/<key>.mp3 and audio/manifest.js.
"""
import argparse, json, os, subprocess, sys, tempfile

import numpy as np
import soundfile as sf
from kokoro_onnx import Kokoro

HERE = os.path.dirname(os.path.abspath(__file__))
AUDIO = os.path.join(HERE, '..', 'audio')

# Animal noises that the phonemizer would otherwise spell out letter by letter.
PHONEMES = {
    'Grrr!': 'ɡˈɜːɹɹɹ!',
    'Mmm, yum yum!': 'mmmmmmmm, jˈʌm jˈʌm!',
    'Awoooooo!': 'ɐwˈuːuːuːuː!',
    'Aaaaaah!': 'ˈɑːɑːɑːɑːɑːɑːh!',
    'Meeow!': 'miˈaʊ!',
}


def ffmpeg(*args):
    subprocess.run(['ffmpeg', '-loglevel', 'error', '-y', *args], check=True)


def render(kokoro, voice, speed, semis, text, out_mp3):
    lang = 'en-gb' if voice.startswith('b') else 'en-us'
    if text in PHONEMES:
        samples, sr = kokoro.create(PHONEMES[text], voice=voice, speed=speed, lang=lang, is_phonemes=True)
    else:
        samples, sr = kokoro.create(text, voice=voice, speed=speed, lang=lang)
    with tempfile.TemporaryDirectory() as tmp:
        wav = os.path.join(tmp, 'a.wav')
        sf.write(wav, np.asarray(samples, dtype=np.float32), sr)
        ratio = 2 ** (semis / 12)
        # Pitch-shift without changing speed, trim silence, even out loudness.
        chain = [f'asetrate={int(sr * ratio)}', f'aresample={sr}', f'atempo={1 / ratio:.5f}'] if semis else []
        chain += ['silenceremove=start_periods=1:start_threshold=-50dB',
                  'areverse', 'silenceremove=start_periods=1:start_threshold=-50dB', 'areverse',
                  'loudnorm=I=-18:TP=-2:LRA=11', f'aresample={sr}']
        ffmpeg('-i', wav, '-af', ','.join(chain), '-ac', '1', '-c:a', 'libmp3lame', '-b:a', '48k', out_mp3)
    probe = subprocess.run(['ffprobe', '-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', out_mp3],
                           capture_output=True, text=True, check=True)
    return round(float(probe.stdout.strip()), 3)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('lines')
    ap.add_argument('--model', default='kokoro.onnx')
    ap.add_argument('--voices', default='voices.bin')
    args = ap.parse_args()

    data = json.load(open(args.lines))
    cast, lines = data['cast'], data['lines']
    os.makedirs(AUDIO, exist_ok=True)
    manifest_path = os.path.join(AUDIO, 'manifest.js')
    manifest = {}
    if os.path.exists(manifest_path):
        raw = open(manifest_path).read()
        manifest = json.loads(raw[raw.index('{'):raw.rindex('}') + 1])

    kokoro = Kokoro(args.model, args.voices)
    wanted = {l['key'] for l in lines}
    for i, l in enumerate(lines, 1):
        mp3 = os.path.join(AUDIO, l['key'] + '.mp3')
        if l['key'] in manifest and os.path.exists(mp3):
            continue
        voice, speed, semis = cast[l['voice']]
        manifest[l['key']] = render(kokoro, voice, speed, semis, l['text'], mp3)
        print(f"[{i}/{len(lines)}] {l['voice']:8} {manifest[l['key']]:6.2f}s  {l['text'][:70]}", flush=True)

    for key in list(manifest):
        if key not in wanted:
            manifest.pop(key)
            p = os.path.join(AUDIO, key + '.mp3')
            if os.path.exists(p):
                os.remove(p)
    with open(manifest_path, 'w') as f:
        f.write('/* Generated by tools/record.py: clip key -> seconds */\nwindow.AUDIO = ')
        json.dump(dict(sorted(manifest.items())), f, separators=(',', ':'))
        f.write(';\n')
    print('done', len(manifest), 'clips')


if __name__ == '__main__':
    sys.exit(main())
