/* Shared by the page and tools/extract-lines.js, so both agree on clip names. */
window.parseLine = function (str) {
  return String(str || '').split('|').map(part => {
    const m = part.match(/^\s*@(\w+):([\s\S]*)$/);
    return m ? { voice: m[1], text: m[2].trim(), dlg: true } : { voice: 'n', text: part.trim(), dlg: false };
  }).filter(s => s.text);
};
window.clipKey = function (voice, text) {   // FNV-1a over code points
  let h = 0x811c9dc5;
  for (const ch of voice + '|' + text) { h ^= ch.codePointAt(0); h = Math.imul(h, 0x01000193) >>> 0; }
  return h.toString(16).padStart(8, '0');
};
