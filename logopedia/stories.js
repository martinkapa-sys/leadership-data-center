/* =========================================================
   Story Stage: the fairy tales
   ---------------------------------------------------------
   Lines can mix the storyteller and characters. Segments are
   separated by "|", and "@voice:" marks a character speaking:
     "The wolf knocked.|@wolf:Little pig, let me come in!"
   Every line is pre-recorded (audio/), keyed by voice + text,
   so changing a line needs a new recording (see README).

   Scene types:
     tell   – narration only
     sound  – the child copies the character's sound 3 times
     tap    – mouth/tongue game: do the move, then tap a target
     blow   – breathing game: blow (or tap) to clear targets
     finale – curtain call with the whole cast
   Other fields:
     actor / with   main character, and a second one beside it
     scale          size of the main character (1 = normal)
     set            extra scenery: [art, x %, ground y %, height %, layer]
     sound / model  bubble text / what the character says as a model
     voice          who says the model sound (default: narrator)
     fric           'z' or 'sh': play a shaped hiss instead of a voice
     exit           how targets leave: feed, float, drift, melt
   ========================================================= */
